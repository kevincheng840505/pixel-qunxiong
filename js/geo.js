export function hash(x, y, seed = 0) {
  let h = (Math.round(x * 1000) * 374761393 + Math.round(y * 1000) * 668265263 + seed * 982451653) >>> 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}
function ihash(x, y, seed) {
  let h = (x * 374761393 + y * 668265263 + seed * 982451653) >>> 0;
  h = Math.imul(h ^ (h >>> 13), 1274126177);
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}
export function smooth(x, y, s, seed) {
  const x0 = Math.floor(x / s), y0 = Math.floor(y / s);
  let fx = x / s - x0, fy = y / s - y0;
  fx = fx * fx * (3 - 2 * fx); fy = fy * fy * (3 - 2 * fy);
  const a = ihash(x0, y0, seed), b = ihash(x0 + 1, y0, seed), c = ihash(x0, y0 + 1, seed), d = ihash(x0 + 1, y0 + 1, seed);
  return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy;
}
export function fbm(x, y, seed) {
  return smooth(x, y, 40, seed) * 0.5 + smooth(x, y, 16, seed + 1) * 0.28 + smooth(x, y, 6, seed + 2) * 0.14 + smooth(x, y, 3, seed + 3) * 0.08;
}

