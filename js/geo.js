const RANGES_XY = RANGES.map(([lon, lat, rx, ry, h]) => { const [x, y] = toXY(lon, lat); return { x, y, rx: rx * 19.2, ry: ry * 15, h }; });

export function elevation(x, y) {
  let e = fbm(x * 2, y * 2, 7) * 0.4;
  for (const r of RANGES_XY) {
    const dx = (x - r.x) / r.rx, dy = (y - r.y) / r.ry;
    const d = dx * dx + dy * dy;
    if (d < 1) e += (1 - d) * (1 - d) * r.h * (0.6 + fbm(x * 2, y * 2, 31) * 0.8);
  }
  // 西部高原
  if (x < 50) e += (50 - x) / 50 * 0.5;
  return e;
}
